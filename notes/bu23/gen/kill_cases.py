# What a host has that wolf has no meaning for, by number (measured:
# linux in probe-p2.log; macOS on CI).
LINUX_ONLY = [16, 29, 30] + list(range(32, 65))
DARWIN_ONLY = [7, 23, 29]
NO_MEANING = "GNU names a signal here that wolf has no meaning for ([os.signal.set])"

MASK = r"(?m)(?<=[A-Z][A-Z0-9])( +[A-Z][^\n]*)?$"
KEEP_L = "^(EXIT|" + "|".join(NAMES) + ")$"
KEEP_T = "^ *[0-9]+ (EXIT|" + "|".join(NAMES) + ")<MASK>$"


def q(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, str):
        return json.dumps(v)
    if isinstance(v, list):
        return "[" + ", ".join(q(x) for x in v) + "]"
    if isinstance(v, dict):
        return "{ " + ", ".join(f"{k} = {q(x)}" for k, x in v.items()) + " }"
    raise TypeError(v)


class File:
    def __init__(self, head):
        self.out = [head.rstrip("\n") + "\n"]
        self.seen = set()

    def note(self, text):
        self.out.append("\n" + "\n".join("# " + l if l else "#" for l in text.strip().split("\n")) + "\n")

    def case(self, name, args, **keys):
        assert name not in self.seen, name
        self.seen.add(name)
        lines = ["", "[[case]]", f"name = {q(name)}", f"args = {q(list(args))}"]
        for k, v in keys.items():
            lines.append(f"{k} = {q(v)}")
        self.out.append("\n".join(lines) + "\n")

    def write(self, path):
        with open(path, "w") as fh:
            fh.write("".join(self.out))
        return len(self.seen)


def label(args):
    return " ".join(a if a and " " not in a and "\t" not in a and "\n" not in a else json.dumps(a) for a in args) or "(no arguments)"


def skip_for(n):
    """`skip_on` for the signal number `n`: the hosts where GNU names it
    and wolf has no meaning for it."""
    hosts = {}
    if n in LINUX_ONLY:
        hosts["Linux"] = NO_MEANING
    if n in DARWIN_ONLY:
        hosts["Darwin"] = NO_MEANING
    return hosts



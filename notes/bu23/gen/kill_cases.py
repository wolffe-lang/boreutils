for args, ids in ((["0"], ["0"]), (["-0", "0"], ["0"]), (["-s", "TERM", "0"], ["0"]), (["--", "-0"], ["-0"]),
                  (["+0"], ["+0"]), (["00"], ["00"]), (["--", "-1"], ["-1"]),
                  (["-s", "KILL", "--", "-1"], ["-1"]), (["-KILL", "-1"], ["-1"]),
                  (["-0", "--", "-1"], ["-1"]), ([" -1"], [" -1"]), (["0", "{pid0}"], ["0"])):
    fate = "ended 143" if "{pid0}" in args else "alive"
    k.case("group: " + label(args), args, container=True, gnu=False,
           ours={"exit": 1, "stdout": "", "stderr": "".join(GROUP.format("'" + a + "'") for a in ids),
                 "fates": [fate]})

